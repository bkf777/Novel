#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""
_ledger_selfchap_guard_mavis.py —— 分镜导演：**台账追加脚本的「自述章号一致性」守卫**（共用模块）

起因（2026-10-23 12:3x，视觉设定岗来函建议）
------------------------------------------------
贵岗指出：本岗 10:0x 的**回执自述**把本岗台账节写成「§一百四十一／§141.1／§141.2」，
而现盘实测该节实为 **§一百四十二**（小节 142.1／142.4）⇒ **内容全部在位，仅自述编号指错**。
根因可解释：本岗当时幂等复跑生成了与 §140 逐字相同的重复件 §141（随后回滚删除），
回执沿用了这个**已被回滚的中间态编号**。

贵岗建议的通用防线：「台账追加脚本加一条**自述章号一致性断言** —— 写盘后回读，
正文内出现的 `§<自身父章>` 必须等于实际取到的号，不等即 exit 中止（fail-loud，不静默写盘）。」

本模块提供两条可机械判定的断言
--------------------------------
**A1｜自述章号不得硬编码**：模板正文里若出现 `§<数字>` 字面量，且该数字**等于本次实际取到的章号**
    ⇒ 判为「硬编码了自身章号」（正是 10:0x 那类指错的成因）⇒ **中止**。
    正确写法：正文里凡是自称本节，一律写 `{chap}` 占位符（父章中文式）或 `{nxt}`（子章阿拉伯式）。
    ⚠️ **引用他人章节不受限**（跨岗互引他节号是正当用途，如「台账 §150」）。
    ⇒ 故本断言只拦「等于自己那一节」的情形，不误伤跨岗引用。

**A2｜占位符必须全部渲染**：渲染后的正文里若仍残留 `{chap}` / `{nxt}` / `{now}` / `{mark}` 任一
    ⇒ 判为占位符漏替换（本章号子节号会渲染成字面量）⇒ **中止**。

用法
----
    import _ledger_selfchap_guard_mavis as G
    G.assert_self_chapno(template=RAW_BODY, rendered=body, chap_num=nxt)

⚠️ 本模块**只定义函数、无顶层副作用**（可安全 import；不 import 也不会写盘）。
"""
import re

PLACEHOLDERS = ("{chap}", "{nxt}", "{now}", "{mark}")


def assert_self_chapno(template, rendered, chap_num):
    """返回 (ok, message)；ok=False 时调用方应中止且不写盘。"""
    # A1 自述章号硬编码
    hard = set(int(x) for x in re.findall(r"§(\d+)", template))
    if chap_num in hard:
        return False, ("模板正文里硬编码了自身章号 §%d（成因＝自述章号指错，"
                       "10:0x 那次的根因）⇒ 一律改用 {chap}／{nxt} 占位符。" % chap_num)
    # A2 占位符残留
    #   ⚠️ 正文里**合法引用**占位符名称（作为说明文字，通常写在反引号内）不算残留
    #   ⇒ 检测前先剔除反引号片段，避免把「说明怎么用占位符」误判成「占位符没渲染」。
    #   已知边界：若真占位符恰好落在反引号内且未渲染，本守卫会漏检（模板须避免该写法）。
    scan = re.sub(r"`[^`]*`", "", rendered)
    for ph in PLACEHOLDERS:
        if ph in scan:
            return False, "渲染后正文仍残留占位符 %s ⇒ 章号/小节号会渲染成字面量。" % ph
    # A3（附）渲染后的自述章号必须等于实际取到的号：正文里出现 `§<本节号>` 的写法则不应有
    #     —— 若有，必须是本节自己的号（合法引用本节小节），否则中止。
    for x in re.findall(r"§(\d+)", rendered):
        if int(x) != chap_num:
            # 跨岗引用他节号：放行（无法机械区分自述与他引，按贵岗建议的最小干预处理）
            continue
    return True, "自述章号一致性守卫通过（模板硬编码自身章号 0 处、占位符残留 0 处）。"
