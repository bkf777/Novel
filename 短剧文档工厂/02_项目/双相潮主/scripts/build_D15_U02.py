def build_voice_over(d04, d09, d16):
    """配音表：at_sec／dur_sec 直接取 D16 对白字幕的 in_sec／out_sec（标称 0.1s 网格），
    音色锁 D04 appearance.voice、语速承 D09 语气卡、语气承 D09 对白行。"""
    chars = {c["id"]: c for c in d04["characters"]}
    cards = {c["char_id"]: c for c in d09["voice_cards"]}
    lines = {(l["ep"], l["idx"]): l for l in d09["lines"]}

    def rule_of(card, prefix):
        for r in card["tone_rules"]:
            if r.startswith(prefix):
                return r.split("：", 1)[1] if "：" in r else r
        return ""

    def avoid_of(card):
        for r in card["tone_rules"]:
            if ("禁区" in r) and ("情绪" in r or "句式" in r):
                return r.split("：", 1)[1] if "：" in r else r
        return ""

    out = []
    for ep in d16["episodes"]:
        e = ep["ep"]
        for ln in ep["subtitle_style"].get("lines", []):
            if ln.get("type") != "对白":
                continue
            cid = ln.get("char_id")
            def _norm(x):
                return (x or "").strip().strip("「」")
            cand = [k for k in lines
                     if k[0] == e and _norm(lines[k]["text"]) == _norm(ln.get("text"))]
            if not cand:
                continue
            idx = cand[0][1]
            ln09 = lines[(e, idx)]
            ch = chars[cid]
            card = cards.get(cid, {"tone_rules": []})
            at = round(round(float(ln["in_sec"]) / 0.1) * 0.1, 1)
            dur = round(round((float(ln["out_sec"]) - float(ln["in_sec"])) / 0.1) * 0.1, 1)
            out.append(vo(cid, e, idx, ln.get("shot_id"), at, dur, ln09.get("tone"),
                          ch["appearance"].get("voice"),
                          rule_of(card, "语速"),
                          avoid_of(card)))
    return out


def inject_voice_and_load(d16):
    """按集装配 voice_over，并按 D16 对白行数给每段 BGM 算台词让位量。"""
    for ep in EPISODES:
        e = ep["ep"]
        d16e = next(x for x in d16["episodes"] if x["ep"] == e)
        subs = [l for l in d16e["subtitle_style"].get("lines", []) if l.get("type") == "对白"]
        for bc in ep["bgm_curve"]:
            n = sum(1 for l in subs
                    if bc["start_sec"] <= float(l["in_sec"]) < bc["end_sec"])
            bc["dialogue_lines"] = n
            bc["duck_db"] = 0 if n == 0 else (3 if n == 1 else 6)
            bc["duck_rule"] = (
                "本段无台词，BGM 全幅保留"
                if n == 0 else
                "本段 %d 句台词，BGM 在台词起音前 0.2s 下沉 %ddB，台词收音后 0.3s 渐变回升" % (n, bc["duck_db"])
            )


