# ── 结构构造器 ───────────────────────────────────────────────────────────────────
def sfx(shot_id, g, at, dur, event, typ, level, mix=None):
    d = {"shot_id": shot_id, "global_shot_no": g, "at_sec": at, "dur_sec": dur,
         "event": event, "type": typ, "level_db": level}
    if mix:
        d["mix"] = mix
    return d


def foley(shot_id, g, at, dur, event, level, mix=None):
    d = {"shot_id": shot_id, "global_shot_no": g, "at_sec": at, "dur_sec": dur,
         "event": event, "type": "拟音", "level_db": level}
    if mix:
        d["mix"] = mix
    return d


def bgm(seg, name, s, e, goal, emotion, intensity, motif, arrangement):
    return {"segment": seg, "segment_name": name, "start_sec": s, "end_sec": e,
            "emotion_goal_ref": goal, "emotion": emotion, "intensity": intensity,
            "motif": motif, "arrangement": arrangement}


def vo(char_id, ep, idx, shot_id, at_sec, dur_sec, tone, voice_lock, pace, avoid):
    return {
        "char_id": char_id, "ep": ep, "line_ref": "D09 ep%d #%d" % (ep, idx),
        "shot_id": shot_id, "at_sec": at_sec, "dur_sec": dur_sec,
        "voice_lock": voice_lock, "pace": pace, "tone": tone,
        "level_db": -18,
        "mix": "人声轨独立成轨；起音前 0.2s 环境层与能量层压低 6dB，收音后 0.3s 渐变恢复；字幕不得早于配音起音，出点不早于配音收音。",
        "avoid": avoid,
    }


