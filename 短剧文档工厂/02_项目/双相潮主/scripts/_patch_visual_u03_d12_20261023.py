def main(dry_run=False):
    for unit, patches in PATCHES.items():
        path = os.path.join(PROJ, "scripts", f"d12_content_{unit}.py")
        with open(path, encoding="utf-8") as f:
            src = f.read()
        for old, new in patches:
            n = src.count(old)
            if n != 1:
                print(f"[FAIL] {unit}: 目标串命中 {n} 次（要求恰好 1 次）→ {old[:60]}...")
                sys.exit(1)
            src = src.replace(old, new)
        if dry_run:
            print(f"[dry-run] {unit}: {len(patches)} 处替换已就绪，未写盘")
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(src)
        print(f"[OK] {unit}: {len(patches)} 处替换已写入 {path}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    main(a.dry_run)
