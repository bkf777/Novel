def _vkey(v):
    """版本号 → 可比较的 (主, 次) 元组；非 vX.Y 形式一律按 (0, 0) 视作最低。"""
    m = re.match(r"^v?(\d+)\.(\d+)$", str(v or ""))
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


