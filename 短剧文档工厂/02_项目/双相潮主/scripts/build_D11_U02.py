    #    ⚠️ 提取必须**括号配平**：D07 段 note 本身可能内含「」
    #       （如 ep013 段1「摊位支起，「无垢净髓」四个字压在电子屏下方…」），
    #       朴素正则 `「([^」]*)」` 会在内层 」 处截断，把正确引文误判为不符。
    def _extract_d07_quote(note, seg_no):
        pre = f"D07 段{seg_no}「"
        i = note.find(pre)
        if i < 0:
            return None
        j = i + len(pre)
        depth = 1
        while j < len(note):
            c = note[j]
            if c == "「":
                depth += 1
            elif c == "」":
                depth -= 1
                if depth == 0:
                    return note[i + len(pre):j]
            j += 1
        return None

