def main():
    fp0 = fingerprint(P)
    with open(P, encoding="utf-8") as f:
        d = json.load(f)
    print(f"   基线：D18 v{fp0['version']} {fp0['size']} B sha16={fp0['sha16']}")

    changed = False
    for coll, item in (("global_checks", Q100), ("global_checks", Q106),
                       ("open_issues", R40), ("open_issues", R43), ("open_issues", R42)):
        lst = d.setdefault(coll, [])
        if any(x.get("id") == item["id"] for x in lst):
            print(f"   ⏭  {item['id']} 已在册，跳过")
            continue
        lst.append(item)
        changed = True
        print(f"   ✅ 追加 {coll} · {item['id']}")

    if not changed:
        print("   无变化，不写盘")
        return
    v = re.sub(r"^v+", "v", str(d.get("version", "v1.0")))
    d["version"] = f"{v.split('.')[0]}.{int(v.split('.')[1]) + 1}"
    if DRY:
        print(f"   [dry-run] 将写 D18 v{d['version']}")
        return
    now = fingerprint(P)
    if now != fp0:
        print(f"❌ 并发守卫：D18 在读盘后被改动（{fp0} → {now}）⇒ 放弃写盘")
        sys.exit(1)
    os.makedirs(BAK, exist_ok=True)
    shutil.copy2(P, os.path.join(BAK, "D18.json"))
    with open(P, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    print(f"   ✅ 写 D18.json（v{d['version']}）｜备份 {BAK}")


if __name__ == "__main__":
    main()
