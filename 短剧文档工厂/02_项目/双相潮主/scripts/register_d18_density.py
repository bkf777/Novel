def fingerprint(p):
    b = open(p, "rb").read()
    o = json.loads(b.decode("utf-8"))
    return {"version": o.get("version"), "size": len(b),
            "sha16": hashlib.sha256(b).hexdigest()[:16],
            "mtime": os.path.getmtime(p)}


