def cn2int(s):
    if s.isdigit(): return int(s)
    d={"零":0,"一":1,"二":2,"三":3,"四":4,"五":5,"六":6,"七":7,"八":8,"九":9}; u={"十":10,"百":100,"千":1000}
    t=sec=0
    for ch in s:
        if ch in d: sec=d[ch]
        elif ch in u:
            x=u[ch]
            if sec==0: sec=1
            t+=sec*x; sec=0
        else: return None
    return t+sec
