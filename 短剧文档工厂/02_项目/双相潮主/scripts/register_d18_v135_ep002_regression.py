def assert_marker_ids_aligned(d):
    """落盘前自检：任一条目的 marker 编号与自身 id 编号不一致 ⇒ 中止写盘。"""
    bad = []
    for e in d.get("open_issues", []):
        eid = e.get("id") or ""
        m = re.match(r"^(U\d\d-R(\d+))$", eid)
        if not m:
            continue
        for mk in re.findall(r"【(U\d\d-R(\d+))-[^】]+】",
                             json.dumps(e, ensure_ascii=False)):
            if mk[1] != m.group(2):
                bad.append((eid, mk[1]))
    for c in d.get("global_checks", []):
        cid = c.get("id") or ""
        if not re.match(r"^Q\d+$", cid):
            continue
        for mk in re.findall(r"【Q(\d+)-[^】]+】", json.dumps(c, ensure_ascii=False)):
            if mk != cid[1:]:
                bad.append((cid, mk))
    if bad:
        for eid, mk in bad:
            print(f"❌ marker 编号与 id 不同号：条目 id={eid} 挂 marker 编号 {mk}")
        print("❌ 中止写盘：须先把 marker 编号改到与 id 同号（或改用无编号 marker）")
        return False
    return True


def backfill_markers(d, specs, section, field):
    """一次性回填：已写入但当时漏带 marker 的条目，追加式补上 marker（原文保留）。"""
    n = 0
    for spec in specs:
        match = spec.get("match")
        if not match:
            continue
        for entry in d.get(section, []):
            if has_marker(entry, spec["marker"]):
                continue
            body = " ".join(str(v) for v in entry.values())
            if match in body:
                entry[field] = (entry.get(field) or "") + f"\n\n{spec['marker']}"
                n += 1
    return n


