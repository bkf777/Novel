def selfcheck():
    errs = []
    d04 = json.load(open(os.path.join(PROJ, "shared/D04.json"), encoding="utf-8"))
    d11 = json.load(open(os.path.join(PROJ, "units/U03/D11.json"), encoding="utf-8"))
    d07 = json.load(open(os.path.join(PROJ, "units/U03/D07.json"), encoding="utf-8"))
    d09 = json.load(open(os.path.join(PROJ, "units/U03/D09.json"), encoding="utf-8"))
    char_ids = {c["id"] for c in d04["characters"]}
    d11map = {e["ep"]: e for e in d11["episodes"]}
    d07map = {e["ep"]: e for e in d07["episodes"]}
    d09lines = {(l["ep"], l["idx"]): l for l in d09["lines"]}
    shot_range = {}
    for e in d11["episodes"]:
        t = 0.0
        for s in e["shots"]:
            shot_range[(e["ep"], s["shot_id"])] = (t, t + s["duration_sec"])
            t += s["duration_sec"]

    text = json.dumps(DOC, ensure_ascii=False)
    for w in BANNED:
        if w in text:
            errs.append("命中禁写词：%s" % w)

    # ── 硬校验 A：sfx 必须逐镜覆盖 D11 全部镜位（漏镜即不合格）────────────────
    d16 = json.load(open(os.path.join(PROJ, "units/U03/D16.json"), encoding="utf-8"))
    cuts = {e["ep"]: e["cuts"] for e in d16["episodes"]}
    shot_count = 0
    for e in d11["episodes"]:
        shot_count += len(e["shots"])
        covered = {s["shot_id"] for s in e["shots"]}
        got = {it["shot_id"] for it in next(x for x in DOC["episodes"] if x["ep"] == e["ep"])["sfx"]}
        for sid in sorted(covered - got):
            errs.append("ep%d 镜%d 无 sfx 条目（D11 逐镜覆盖硬性验收点）" % (e["ep"], sid))
    total_sfx = sum(len(e["sfx"]) for e in DOC["episodes"])
    if total_sfx < shot_count:
        errs.append("sfx 总条数 %d 少于镜位数 %d" % (total_sfx, shot_count))

    # ── 硬校验 B：不得在 D16 段间切点两侧产生半截音效 ────────────────────────
    # 只卡段间边界（counted_in_d17_cut_count=true）。段内并行交替点按 D16 口径
    # 不设声音预铺，连续床声跨过属正确写法。
    for ep in DOC["episodes"]:
        for grp in ("sfx", "foley"):
            for it in ep[grp]:
                s, e = it["at_sec"], it["at_sec"] + it["dur_sec"]
                for c in cuts.get(ep["ep"], []):
                    if c["at_sec"] <= s or c["at_sec"] >= e:
                        continue
                    if not c.get("counted_in_d17_cut_count", True):
                        continue
                    if "承 D16" not in (it.get("mix") or ""):
                        errs.append("ep%d %s「%s」跨过段间切点 %.1fs 但未声明为 D16 声音预铺位"
                                    % (ep["ep"], grp, it["event"], c["at_sec"]))

    # ── 硬校验 D：global_shot_no 必须与 D11 的项目全局镜号一致 ──────────
    # 全局镜号跨单元连续编号（U01 1–32／U02 33–64／U03 65–96），
    # 是声音与剪辑画面逐条对位的唯一索引；局部镜号一律不得写入本字段。
    gno = {}
    for e in d11["episodes"]:
        for s in e["shots"]:
            gno[(e["ep"], s["shot_id"])] = s["global_shot_no"]
    for ep in DOC["episodes"]:
        for grp in ("sfx", "foley"):
            for it in ep[grp]:
                if it.get("global_shot_no") != gno.get((ep["ep"], it["shot_id"])):
                    errs.append("ep%d %s 镜%d 的 global_shot_no=%s 与 D11 的 %s 不一致"
                                % (ep["ep"], grp, it["shot_id"],
                                   it.get("global_shot_no"), gno.get((ep["ep"], it["shot_id"]))))

    # ── 硬校验 C：每段 bgm_curve 必须给出台词让位量 ──────────────────────────
    for ep in DOC["episodes"]:
        for bc in ep["bgm_curve"]:
            if "dialogue_lines" not in bc or "duck_db" not in bc:
                errs.append("ep%d 段%d 缺 dialogue_lines / duck_db（台词让位硬约束）"
                            % (ep["ep"], bc["segment"]))
            elif bc["dialogue_lines"] > 0 and bc["duck_db"] <= 0:
                errs.append("ep%d 段%d 有 %d 句台词但 duck_db=0，未为台词下沉"
                            % (ep["ep"], bc["segment"], bc["dialogue_lines"]))

    for ep in DOC["episodes"]:
        n = ep["ep"]
        if ep["bgm_curve"] is None or len(ep["bgm_curve"]) != 4:
            errs.append("ep%d bgm_curve 必须 4 段" % n)
        segs = d07map[n]["quad_segments"]
        for bc, sg in zip(ep["bgm_curve"], segs):
            if bc["start_sec"] != sg["start_sec"] or bc["end_sec"] != sg["end_sec"]:
                errs.append("ep%d 段%d 秒数与 D07 不一致" % (n, sg["index"]))
            if bc["segment_name"] != sg["name"]:
                errs.append("ep%d 段%d 名称与 D07 不一致" % (n, sg["index"]))
        for grp, key in (("sfx", "sfx"), ("foley", "foley")):
            for it in ep[grp]:
                s, e = shot_range[(n, it["shot_id"])]
                if not (s - 0.6 <= it["at_sec"] <= e + 0.6):
                    errs.append("ep%d %s 镜%d 的时码 %.2f 超出镜位区间 %.1f~%.1f" % (n, grp, it["shot_id"], it["at_sec"], s, e))
                if it["event"] is None or not str(it["event"]).strip():
                    errs.append("ep%d %s 镜%d 事件为空" % (n, grp, it["shot_id"]))
        for v in ep.get("voice_over", []):
            if v["char_id"] not in char_ids:
                errs.append("ep%d 配音角色 %s 不在 D04" % (n, v["char_id"]))
            ln = d09lines.get((v["ep"], v["line_idx"] if "line_idx" in v else int(v["line_ref"].split("#")[1])))
            if ln is None:
                errs.append("ep%d voice_over 引用 D09 行不存在：%s" % (n, v["line_ref"]))
            elif ln["char_id"] != v["char_id"]:
                errs.append("ep%d voice_over 角色与 D09 不符：%s" % (n, v["line_ref"]))
        for mn in ep["mix_notes"]:
            if not str(mn).strip():
                errs.append("ep%d mix_notes 存在空串" % n)
    return errs


