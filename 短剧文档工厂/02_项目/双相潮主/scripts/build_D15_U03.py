def inject_dialogue_load():
    """按 D16 对白字幕统计每段台词条数，回填 bgm_curve 的 dialogue_lines / duck_db。
    派活硬约束 5：BGM 在台词密集段必须下沉让位——此处用数据把「让位」写成可校验字段。"""
    d16 = json.load(open(os.path.join(PROJ, "units/U03/D16.json"), encoding="utf-8"))
    d11 = json.load(open(os.path.join(PROJ, "units/U03/D11.json"), encoding="utf-8"))
    shot_seg = {}
    for e in d11["episodes"]:
        t = 0.0
        for s in e["shots"]:
            mid = t + s["duration_sec"] / 2.0
            for q in QUAD.get(str(e["ep"]), []):
                if q["start_sec"] <= mid < q["end_sec"]:
                    shot_seg[(e["ep"], s["shot_id"])] = q["index"]
                    break
            t += s["duration_sec"]
    dlg = {}
    for e in d16["episodes"]:
        for l in e["subtitle_style"]["lines"]:
            if l.get("type") != "对白":
                continue
            seg = shot_seg.get((e["ep"], l.get("shot_id")))
            if seg:
                dlg[(e["ep"], seg)] = dlg.get((e["ep"], seg), 0) + 1
    for ep in EPISODES:
        for bc in ep["bgm_curve"]:
            n = dlg.get((ep["ep"], bc["segment"]), 0)
            bc["dialogue_lines"] = n
            bc["duck_db"] = 0 if n == 0 else (3 if n == 1 else 6)
            bc["duck_rule"] = (
                "本段无台词，BGM 全幅保留"
                if n == 0
                else "本段 %d 句台词，BGM 在台词起音前 0.2s 下沉 %ddB，台词收音后 0.3s 渐变回升"
                     % (n, bc["duck_db"])
            )


inject_dialogue_load()

